import pytest
from alembic import command
from sqlalchemy import Connection, inspect, text

from app.models import Base

pytestmark = pytest.mark.integration

MODELS_SCHEMA = "models_check"

# Postgres' own rendering of every constraint, index and column default in a schema.
DEFINITIONS = text(
    """
    SELECT 'constraint', r.relname || '.' || c.conname, pg_get_constraintdef(c.oid)
    FROM pg_constraint c
    JOIN pg_class r ON r.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = r.relnamespace
    WHERE n.nspname = :schema AND r.relname <> 'alembic_version'
    UNION ALL
    SELECT 'index', tablename || '.' || indexname, indexdef
    FROM pg_indexes
    WHERE schemaname = :schema AND tablename <> 'alembic_version'
    UNION ALL
    SELECT 'column', table_name || '.' || column_name,
           concat_ws(' ', data_type, is_nullable, column_default)
    FROM information_schema.columns
    WHERE table_schema = :schema AND table_name <> 'alembic_version'
    """
)


def table_names(engine) -> set[str]:
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def definitions(connection: Connection, schema: str) -> dict[tuple[str, str], str]:
    rows = connection.execute(DEFINITIONS, {"schema": schema})
    return {(kind, name): definition.replace(f"{schema}.", "") for kind, name, definition in rows}


def test_upgrade_creates_every_table_from_an_empty_database(migrated_database):
    assert table_names(migrated_database) == set(Base.metadata.tables)


def test_models_match_the_migrations(migrated_database, alembic_config):
    # Fails with AutogenerateDiffsDetected when a model changes without a migration.
    command.check(alembic_config)


def test_constraints_indexes_and_defaults_match_the_models(migrated_database):
    # alembic check skips CHECK constraints, index predicates and defaults, so build the
    # models in a second schema and compare what Postgres stores for each.
    with migrated_database.connect() as connection:
        connection.execute(text(f"CREATE SCHEMA {MODELS_SCHEMA}"))
        try:
            models = connection.execution_options(schema_translate_map={None: MODELS_SCHEMA})
            Base.metadata.create_all(models)

            assert definitions(connection, MODELS_SCHEMA) == definitions(connection, "public")
        finally:
            connection.execute(text(f"DROP SCHEMA {MODELS_SCHEMA} CASCADE"))
            connection.commit()


def test_downgrade_removes_every_table_and_upgrade_runs_again(migrated_database, alembic_config):
    command.downgrade(alembic_config, "base")
    assert table_names(migrated_database) == set()

    command.upgrade(alembic_config, "head")
    assert table_names(migrated_database) == set(Base.metadata.tables)
